// Inserter.swift — reads what's in the text box, and puts the new text into it.
//
// Pasting is the one way that works everywhere (native boxes, web pages, Electron, rich editors keep
// their formatting and undo). The clipboard is put back as it was a moment later, and the pasted text is
// marked transient so clipboard managers skip it.

import AppKit
import ApplicationServices
import Carbon.HIToolbox

enum Inserter {
    /// The last text Penlight wrote, for "Copy last result".
    private(set) static var last = ""

    /// What's already in the box, and how the new text should go in.
    static func field(_ t: Target) -> FieldText {
        let value = AX.string(t.element, kAXValueAttribute) ?? ""
        let selected = AX.string(t.element, kAXSelectedTextAttribute)
        return FieldText.read(value: value, selected: selected, cursor: AX.selectedRange(t.element)?.location)
    }

    /// Puts `text` into the box. `done(true)` if the box changed (or we can't tell), false if it clearly didn't.
    static func insert(_ text: String, into t: Target, mode: FieldText.Mode, done: @escaping (Bool) -> Void) {
        last = text
        let before = AX.string(t.element, kAXValueAttribute)
        let pb = NSPasteboard.general
        let saved = snapshot(pb)
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
            item.setString("", forType: NSPasteboard.PasteboardType(marker))
        }
        pb.writeObjects([item])
        let ours = pb.changeCount

        NSRunningApplication(processIdentifier: t.pid)?.activate()
        AX.set(t.element, kAXFocusedAttribute, kCFBooleanTrue)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            if mode == .whole { selectAll(t) }
            key(kVK_ANSI_V)
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) {
                if pb.changeCount == ours { restore(saved, to: pb) }
                if changed(t, from: before) { done(true); return }
                // ⌘V did nothing (no Edit menu, or the app ignores synthetic keys): write it through Accessibility.
                if mode == .whole { selectAll(t, keys: false) }
                AX.set(t.element, kAXSelectedTextAttribute, text as CFString)
                done(changed(t, from: before))
            }
        }
    }

    private static func changed(_ t: Target, from before: String?) -> Bool {
        let after = AX.string(t.element, kAXValueAttribute)
        return before == nil || after == nil || after != before
    }

    /// Selects the box's whole text: through Accessibility when the app allows it, else ⌘A.
    private static func selectAll(_ t: Target, keys: Bool = true) {
        let len = ((AX.string(t.element, kAXValueAttribute) ?? "") as NSString).length
        var r = CFRange(location: 0, length: len)
        if len > 0, let v = AXValueCreate(.cfRange, &r) {
            AX.set(t.element, kAXSelectedTextRangeAttribute, v)
            if AX.selectedRange(t.element)?.length == len { return }
        }
        if keys { key(kVK_ANSI_A) }
    }

    /// Presses ⌘ + a key in the frontmost app.
    private static func key(_ code: Int) {
        let src = CGEventSource(stateID: .hidSystemState)
        for down in [true, false] {
            let e = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(code), keyDown: down)
            e?.flags = .maskCommand
            e?.post(tap: .cghidEventTap)
        }
    }

    static func copy(_ text: String) {
        last = text
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    // MARK: Clipboard save / restore (every item, every type)

    private static func snapshot(_ pb: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pb.pasteboardItems ?? []).map { item in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types { if let data = item.data(forType: t) { d[t] = data } }
            return d
        }
    }
    private static func restore(_ items: [[NSPasteboard.PasteboardType: Data]], to pb: NSPasteboard) {
        pb.clearContents()
        guard !items.isEmpty else { return }
        pb.writeObjects(items.map { d in
            let item = NSPasteboardItem()
            for (t, data) in d { item.setData(data, forType: t) }
            return item
        })
    }
}
